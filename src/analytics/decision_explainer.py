"""
Decision Explainer Module for AI-Based Intelligent Trading System.
=================================================================
Produces grounded, human-readable, plain-English explanations for BUY, HOLD, and SELL
decisions generated by the Multi-Modal Decision Fusion engine.

Adheres to:
1. Strict factual grounding: Explanations are derived exclusively from real model outputs,
   technical features, news articles, and fusion contributions.
2. Zero hallucinations: Never invents confidence numbers, probabilities, future price targets,
   or causal relationships.
3. Separation of sentiment and trading signals: Explains how news contributed to the score
   without confusing reported media tone with guaranteed price direction.
4. Transparent model consensus: Explains exact agreement or conflict among Classification (35%),
   Reinforcement Learning (30%), Market Regime (15%), and News Sentiment (20%).
5. Offline analytical fallback: 100% deterministic local generation with optional LLM enhancement.
"""

